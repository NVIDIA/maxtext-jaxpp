"""Derive CUDA13 requirements from the checked-in CUDA12 dependency snapshot.

Keep shared packages and environment markers unchanged. CUDA runtime packages
have different names and version numbering, so translate them explicitly rather
than replacing every occurrence of 'cu12'. Run this after regenerating CUDA12:

  python3 src/dependencies/scripts/generate_cuda13_requirements.py
  python3 src/dependencies/scripts/generate_cuda13_requirements.py --check
"""

import argparse
from pathlib import Path
import re
import sys

GENERATED_DIR = Path(__file__).resolve().parents[1] / "requirements" / "generated_requirements"
SOURCE_FILE = GENERATED_DIR / "cuda12-requirements.txt"
OUTPUT_FILE = GENERATED_DIR / "cuda13-requirements.txt"

RENAMED_PACKAGES = {
    "jax-cuda12-pjrt": "jax-cuda13-pjrt",
    "jax-cuda12-plugin": "jax-cuda13-plugin",
    "nvidia-cublas-cu12": "nvidia-cublas",
    "nvidia-cuda-cupti-cu12": "nvidia-cuda-cupti",
    "nvidia-cuda-nvcc-cu12": "nvidia-cuda-nvcc",
    "nvidia-cuda-nvrtc-cu12": "nvidia-cuda-nvrtc",
    "nvidia-cuda-runtime-cu12": "nvidia-cuda-runtime",
    "nvidia-cudnn-cu12": "nvidia-cudnn-cu13",
    "nvidia-cufft-cu12": "nvidia-cufft",
    "nvidia-cusolver-cu12": "nvidia-cusolver",
    "nvidia-cusparse-cu12": "nvidia-cusparse",
    "nvidia-nccl-cu12": "nvidia-nccl-cu13",
    "nvidia-nvjitlink-cu12": "nvidia-nvjitlink",
    "nvidia-nvshmem-cu12": "nvidia-nvshmem-cu13",
    "transformer-engine-cu12": "transformer-engine-cu13",
}
# CUDA13 SDK versions are not comparable to CUDA12 SDK versions. Retain the
# existing CUDA13 toolkit floors and meet JAX 0.11.1's CUDA13 library minimums
# (https://pypi.org/pypi/jax-cuda13-plugin/0.11.1/json).
CUDA13_VERSION_FLOORS = {
    "nvidia-cublas": "13.4.1.1",
    "nvidia-cuda-cupti": "13.2.75",
    "nvidia-cuda-nvcc": "13.2.78",
    "nvidia-cuda-nvrtc": "13.2.78",
    "nvidia-cuda-runtime": "13.2.75",
    "nvidia-cufft": "12.0.0.15",
    "nvidia-cusolver": "12.0.3.29",
    "nvidia-cusparse": "12.6.2.49",
    "nvidia-nvjitlink": "13.2.78",
}
# CUDA13 NVCC uses these separate wheels. CUDA12 NVCC bundles their equivalents.
EXTRA_PACKAGES = (
    "nvidia-cuda-crt>=13.2.75 ; sys_platform == 'linux'",
    "nvidia-nvvm>=13.2.78 ; sys_platform == 'linux'",
)
# The unsuffixed CCCL distribution is already in the CUDA12 snapshot. CUTLASS
# intentionally ships both runtime variants, so its cu12 package must stay.
REMOVED_PACKAGES = {"nvidia-cuda-cccl-cu12"}
KEPT_CUDA12_PACKAGES = {"nvidia-cutlass-dsl-libs-cu12"}
HEADER = (
    "# Generated by generate_cuda13_requirements.py from cuda12-requirements.txt. Do not edit manually.\n"
    "# Shared dependency versions follow the CUDA12 snapshot; CUDA runtime packages are translated explicitly.\n\n"
)
_NAME = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)")


def render_cuda13_requirements(source: str) -> str:
  """Translate a flat generated requirements snapshot without changing shared dependencies."""
  requirements = {}
  for line in source.splitlines():
    line = line.strip()
    if not line or line.startswith("#"):
      continue
    match = _NAME.match(line)
    if match is None or not re.search(r"[<>=!~]", line):
      raise ValueError(f"Expected a flat versioned requirement, got {line!r}")
    name = match.group(1).lower().replace("_", "-")
    if name in REMOVED_PACKAGES:
      continue
    if name.endswith("-cu12") and name not in RENAMED_PACKAGES and name not in KEPT_CUDA12_PACKAGES:
      raise ValueError(f"Add an explicit CUDA13 mapping for {name}")
    target = RENAMED_PACKAGES.get(name, name)
    if target in requirements:
      raise ValueError(f"Duplicate translated requirement: {target}")
    translated = target + line[match.end() :]
    if target in CUDA13_VERSION_FLOORS:
      marker = " ;" + line.split(";", 1)[1] if ";" in line else ""
      translated = f"{target}>={CUDA13_VERSION_FLOORS[target]}{marker}"
    requirements[target] = translated
  for line in EXTRA_PACKAGES:
    name = _NAME.match(line).group(1)
    if name in requirements:
      raise ValueError(f"Duplicate CUDA13 toolkit requirement: {name}")
    requirements[name] = line
  return HEADER + "\n".join(requirements[name] for name in sorted(requirements)) + "\n"


def main() -> int:
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument("--source", type=Path, default=SOURCE_FILE)
  parser.add_argument("--output", type=Path, default=OUTPUT_FILE)
  parser.add_argument("--check", action="store_true", help="Fail if the checked-in CUDA13 requirements are stale")
  args = parser.parse_args()
  expected = render_cuda13_requirements(args.source.read_text(encoding="utf-8"))
  if args.check:
    if not args.output.is_file() or args.output.read_text(encoding="utf-8") != expected:
      print(f"{args.output} is stale; run {Path(__file__).name}.", file=sys.stderr)
      return 1
  else:
    args.output.write_text(expected, encoding="utf-8")
    print(f"Wrote {args.output}")
  return 0


if __name__ == "__main__":
  sys.exit(main())
